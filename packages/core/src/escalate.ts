/**
 * 실행 턴 승격 (cascade).
 *
 * **업계 cascade와 다른 점이 이 모듈의 존재 이유다.** 싸게 시작해서 안 되면 강한 모델로
 * 올리는 구조 자체는 흔하다. 다만 널리 쓰이는 구현은 승격 여부를 **모델의 자기 확신도**
 * (confidence threshold)로 판정한다 — 작업한 쪽이 자기 작업의 합격 여부를 말하는 구조다.
 *
 * zannabi는 게이트를 러너가 직접 돌리므로 **프로세스 밖 종료코드**라는 객관 신호를 갖는다.
 * 그래서 승격 신호를 새로 발명하지 않는다: 이미 있는 정체 감지(`progress.ts`)가 그대로
 * 승격 신호다. **"연속 N라운드 동안 변경분과 게이트 결과가 똑같다"는 것은 이 실행자로는
 * 이 문제를 못 푼다는 관측된 사실**이고, 그것이 지금까지는 중단 사유였을 뿐이다.
 *
 * ## 무엇으로 올리는가 — 계획 런타임으로만 올린다
 *
 * 러너는 **모델 등급표를 갖지 않는다.** "무엇이 더 강한가"를 도구가 안다고 주장하면
 * 모델이 바뀔 때마다 그 주장이 틀리고, 틀린 등급으로 조용히 비싼 모델을 부르게 된다.
 * 대신 이미 사람이 표명한 판단 하나를 쓴다 — **사용자가 계획 턴에 고른 런타임**이다.
 * 실측이 "계획은 낮추지 마라"였으므로 그 자리는 대개 강한 모델이고, 무엇보다
 * **그 선택은 사람이 했다.**
 *
 * 따라서 계획과 실행이 같은 런타임이면 올릴 곳이 없다. 그때는 승격하지 않고 그 사실을 말한다 —
 * 조용히 아무 일도 안 하면 사용자는 승격이 걸린 줄 알고 돌린다.
 *
 * ## 한 번만
 *
 * 승격은 실행당 한 번이다. 올라갈 데가 하나뿐이라 두 번째는 정의되지 않고, 같은 자리를
 * 도는 실행에 강한 모델을 반복 투입하는 것은 예산이 아니라 지출을 태우는 일이다.
 *
 * ## 알고 시작하는 한계
 *
 * 2026-08-20 측정 11회는 **전부 1라운드로 끝났다.** 정체 감지 자체가 아직 실전에서
 * 발동한 적이 없고, 따라서 이 승격도 당분간 발동하지 않는다. 그래서 **기본은 꺼져 있다** —
 * 검증되지 않은 자동 동작이 기본값으로 사람의 지출에 관여해서는 안 된다.
 */

/** 승격이 실제로 일어났다는 기록. 어느 라운드에서 무엇이 무엇으로 바뀌었는지 */
export interface Escalation {
  /** 승격이 적용된 첫 라운드 번호 */
  round: number
  from: string
  to: string
  /** 지금은 정체 하나뿐이다. 신호를 늘릴 때 이 자리가 갈린다 */
  reason: 'no-progress'
}

/** 승격을 걸 수 없는 조합인지와 그 이유. 걸 수 있으면 undefined */
export function escalationBlocked(runtime?: { plan: string; exec: string }): string | undefined {
  if (!runtime) return '런타임 표기가 없어 승격 대상을 알 수 없습니다'
  if (runtime.plan === runtime.exec)
    return (
      `승격을 켰지만 계획과 실행이 같은 런타임입니다(${runtime.plan}) — 올릴 곳이 없습니다.` +
      ' --exec-agent/--exec-model로 실행을 낮춰야 승격할 자리가 생깁니다'
    )
  return undefined
}
